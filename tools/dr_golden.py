"""Writes dead reckoning test cases computed by Open-DIS Python to tests/golden/dr_cases.txt.

Usage: tools/.venv/Scripts/python.exe tools/dr_golden.py

Open-DIS Python (opendis.DeadReckoning) is used as a black box. Its positions are exact for DRM 1-5. For the
rotating algorithms (3, 4) it integrates Euler angle rates linearly, which is only a first-order approximation,
so its orientations are written for small time steps only and compared with a looser tolerance.

One case per line:
  dr algorithm dt  px py pz  vx vy vz  ax ay az  psi theta phi  wx wy wz  ->  px py pz  psi theta phi
"""
import math
import pathlib
import random

from opendis import DeadReckoning as dr

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "golden" / "dr_cases.txt"

ANKARA_ECEF = (4118639.58, 2654282.08, 4069473.68)


def extrapolate(algorithm, dt, p, v, a, o, w):
    if algorithm == 1:
        return dr.drm_static(p, o)
    if algorithm == 2:
        return dr.drm_fpw(p, v, dt, o)
    if algorithm == 3:
        return dr.drm_rpw(p, v, dt, o, w)
    if algorithm == 4:
        return dr.drm_rvw(p, v, a, dt, o, w)
    if algorithm == 5:
        return dr.drm_fvw(p, v, a, dt, o)
    raise ValueError(algorithm)


def main():
    rng = random.Random(1278)
    lines = []
    for algorithm in (1, 2, 3, 4, 5):
        for i in range(20):
            p = [c + rng.uniform(-5000, 5000) for c in ANKARA_ECEF]
            v = [rng.uniform(-300, 300) for _ in range(3)]
            a = [rng.uniform(-20, 20) for _ in range(3)]
            o = [rng.uniform(-math.pi, math.pi), rng.uniform(-1.3, 1.3), rng.uniform(-math.pi, math.pi)]
            w = [rng.uniform(-0.5, 0.5) for _ in range(3)]
            # Rotating algorithms: small steps only (see the module docstring).
            dt = rng.choice([0.001, 0.002, 0.005]) if algorithm in (3, 4) else rng.choice([0.05, 0.2, 1.0, 5.0, 12.0])
            pos, ori = extrapolate(algorithm, dt, p, v, a, o, w)
            values = [algorithm, dt, *p, *v, *a, *o, *w, *map(float, pos), *map(float, ori)]
            lines.append("dr " + " ".join(repr(x) for x in values))
    header = "# Generated by tools/dr_golden.py (Open-DIS Python DeadReckoning). Do not edit.\n"
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} cases -> {OUT}")


if __name__ == "__main__":
    main()
