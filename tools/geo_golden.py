"""Writes coordinate test cases computed by the oracles to tests/golden/geo_cases.txt.

Usage: tools/.venv/Scripts/python.exe tools/geo_golden.py

Positions come from pymap3d (WGS84). DIS Euler angles come from Open-DIS Python
(opendis.RangeCoordinates.GPS.llarpy2ecef), used only as a black box: its code is not copied.

One case per line, whitespace separated, floats written with repr() so they parse back exactly:
  geo    lat_deg lon_deg height_m  x y z
  enu    lat0_deg lon0_deg h0_m  lat_deg lon_deg height_m  east north up
  euler  lat_deg lon_deg  heading pitch roll  psi theta phi      (Euler angles in radians)
"""
import math
import pathlib
import random

import pymap3d
from opendis.RangeCoordinates import GPS

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "golden" / "geo_cases.txt"

ANKARA = (39.9334, 32.8597, 938.0)

NAMED_POINTS = [
    (0.0, 0.0, 0.0),  # equator, prime meridian
    (0.0, 90.0, 0.0),
    (0.0, 180.0, 0.0),  # antimeridian
    (0.0, -179.9999, 100.0),
    (0.0, 179.9999, 100.0),
    (90.0, 0.0, 0.0),  # North Pole
    (-90.0, 0.0, 0.0),  # South Pole
    (89.9999, 45.0, 10.0),  # near the pole
    (-89.9999, -135.0, 10.0),
    ANKARA,
    (41.0082, 28.9784, 40.0),  # Istanbul
    (27.9881, 86.925, 8848.86),  # Everest
    (31.5, 35.5, -430.0),  # Dead Sea, below the ellipsoid
    (-33.8688, 151.2093, 58.0),  # Sydney
    (0.0, 0.0, 400000.0),  # low Earth orbit
    (10.0, -75.0, 35786000.0),  # geostationary altitude
    (45.0, -120.0, -5000.0),  # underground
]


def geo_cases(rng):
    points = list(NAMED_POINTS)
    for _ in range(60):
        points.append((rng.uniform(-90, 90), rng.uniform(-180, 180), rng.uniform(-500, 20000)))
    for lat, lon, h in points:
        x, y, z = pymap3d.geodetic2ecef(lat, lon, h)
        yield f"geo {lat!r} {lon!r} {h!r} {float(x)!r} {float(y)!r} {float(z)!r}"


def enu_cases(rng):
    origins = [ANKARA, (0.0, 179.99, 0.0), (-60.0, -20.0, 500.0)]
    for origin in origins:
        targets = [origin, (origin[0], origin[1], origin[2] + 100.0)]
        for _ in range(15):
            # Up to ~200 km away (scenario scale), plus some aircraft altitudes.
            targets.append((
                max(-90.0, min(90.0, origin[0] + rng.uniform(-1.8, 1.8))),
                origin[1] + rng.uniform(-1.8, 1.8),
                rng.uniform(-100, 12000),
            ))
        for lat, lon, h in targets:
            e, n, u = pymap3d.geodetic2enu(lat, lon, h, *origin)
            yield (f"enu {origin[0]!r} {origin[1]!r} {origin[2]!r} {lat!r} {lon!r} {h!r} "
                   f"{float(e)!r} {float(n)!r} {float(u)!r}")


def euler_cases(rng):
    gps = GPS()
    cases = [
        (0.0, 0.0, math.radians(90), 0.0, 0.0),  # heading east on the equator
        (ANKARA[0], ANKARA[1], 0.0, 0.0, 0.0),  # level, facing north
        (ANKARA[0], ANKARA[1], math.radians(90), 0.0, 0.0),
        (ANKARA[0], ANKARA[1], math.radians(-135), math.radians(10), math.radians(-30)),
        (ANKARA[0], ANKARA[1], math.radians(45), math.radians(60), math.radians(170)),
        (-33.8688, 151.2093, math.radians(200 - 360), math.radians(-20), math.radians(5)),
    ]
    for _ in range(60):
        cases.append((
            rng.uniform(-85, 85), rng.uniform(-180, 180),
            rng.uniform(-math.pi, math.pi), rng.uniform(-1.4, 1.4), rng.uniform(-math.pi, math.pi),
        ))
    for lat, lon, heading, pitch, roll in cases:
        # llarpy2ecef(lat, lon, alt, roll, pitch, yaw), all angles in radians.
        _, _, _, psi, theta, phi = gps.llarpy2ecef(math.radians(lat), math.radians(lon), 0.0, roll, pitch, heading)
        yield (f"euler {lat!r} {lon!r} {heading!r} {pitch!r} {roll!r} "
               f"{float(psi)!r} {float(theta)!r} {float(phi)!r}")


def main():
    rng = random.Random(1278)
    lines = [*geo_cases(rng), *enu_cases(rng), *euler_cases(rng)]
    header = "# Generated by tools/geo_golden.py (pymap3d, Open-DIS Python). Do not edit.\n"
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} cases -> {OUT}")


if __name__ == "__main__":
    main()
